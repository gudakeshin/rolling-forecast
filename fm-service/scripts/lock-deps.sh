#!/usr/bin/env bash
#
# Regenerate fm-service/requirements.lock from requirements.txt.
#
# Resolves for the Docker target (linux/x86_64, CPython 3.11) with the
# CPU-only torch index, so the image never pulls multi-GB CUDA wheels.
# The lock is installed with --require-hashes. EXCLUDE_NEWER holds the
# resolution to releases at least two weeks old; move it forward on purpose.
set -euo pipefail
cd "$(dirname "$0")/.."
command -v uv >/dev/null 2>&1 || { echo "uv is required" >&2; exit 1; }

TMP_OUT="$(mktemp -t fm-lock)"
uv pip compile requirements.txt \
  --python-platform x86_64-manylinux_2_28 --python-version 3.11 \
  --generate-hashes \
  --index-url https://pypi.org/simple \
  --extra-index-url https://download.pytorch.org/whl/cpu \
  --index-strategy unsafe-best-match \
  --emit-index-url \
  --exclude-newer "${EXCLUDE_NEWER:-2026-11-10T00:00:00Z}" \
  --output-file "$TMP_OUT"
{
  echo "# Locked dependency set for fm-service — DO NOT EDIT BY HAND."
  echo "# Regenerate with:  ./scripts/lock-deps.sh   (linux/x86_64, CPython 3.11, CPU torch)"
  grep -v '^#    uv pip compile' "$TMP_OUT" | grep -v '^# This file was autogenerated'
} > requirements.lock
rm -f "$TMP_OUT"
echo "Wrote requirements.lock ($(grep -c '^[a-zA-Z0-9]' requirements.lock) packages)."
